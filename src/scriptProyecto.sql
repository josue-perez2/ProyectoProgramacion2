
CREATE TABLE CLIENTES (
    ID_CLI NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DPI_CLI VARCHAR2 (20) UNIQUE,
    NOMBRE_CLI VARCHAR2 (100) NOT NULL,
    TELEFONO_CLI VARCHAR2 (15),
    CORREO_CLI VARCHAR2 (100) UNIQUE,
    DIRECCION_CLI VARCHAR2 (200),
    SALDO_PUNTO_CLI NUMBER (10) DEFAULT 0 NOT NULL,
    ESTADO_CLI VARCHAR2 (1) DEFAULT 'A' NOT NULL,
    PASSWORD_CLI VARCHAR2 (100),
    TOKEN_CLI VARCHAR2 (100),
    CONSTRAINT CHK_SALDO_PUNTO_CLI CHECK (SALDO_PUNTO_CLI >= 0),
    CONSTRAINT CHK_ESTADO_CLI CHECK (ESTADO_CLI IN ('A', 'I'))
);

CREATE TABLE CATEGORIAS (
    ID_CAT NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_CAT VARCHAR2 (50) NOT NULL
);

CREATE TABLE PRODUCTOS (
    ID_PRO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_PRO VARCHAR2 (30) NOT NULL UNIQUE,
    ID_CAT_PRO NUMBER NOT NULL,
    NOMBRE_PRO VARCHAR2 (100) NOT NULL,
    PRECIO_PRO NUMBER (10, 2) NOT NULL,
    EXISTENCIA_PRO NUMBER (10, 2) DEFAULT 0 NOT NULL,
    ACTIVO_PRO VARCHAR2 (1) DEFAULT 'A' NOT NULL,
    CONSTRAINT FK_PRO_CAT FOREIGN KEY (ID_CAT_PRO) REFERENCES CATEGORIAS (ID_CAT),
    CONSTRAINT CHK_PRECIO_PRO CHECK (PRECIO_PRO >= 0),
    CONSTRAINT CHK_EXISTENCIA_PRO CHECK (EXISTENCIA_PRO >= 0),
    CONSTRAINT CHK_ACTIVO_PRO CHECK (ACTIVO_PRO IN ('A', 'I'))
);

CREATE TABLE SANDWICH (
    ID_SAN NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_SAN VARCHAR2 (30) NOT NULL UNIQUE,
    NOMBRE_SAN VARCHAR2 (100) NOT NULL,
    PRECIO_SAN NUMBER (10, 2) NOT NULL,
    ACTIVO_SAN VARCHAR2 (1) DEFAULT 'A' NOT NULL,
    CONSTRAINT CHK_PRECIO_SAN CHECK (PRECIO_SAN >= 0),
    CONSTRAINT CHK_ACTIVO_SAN CHECK (ACTIVO_SAN IN ('A', 'I'))
);

CREATE TABLE DETALLE_SANDWICH (
    ID_DET_SAN NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_SAN_DET NUMBER NOT NULL,
    ID_PRO_DET NUMBER NOT NULL,
    CANTIDAD_DET NUMBER (10, 2) DEFAULT 1 NOT NULL,
    OBLIGATORIO_DET VARCHAR2 (1) DEFAULT 'N' NOT NULL,
    CONSTRAINT FK_DET_SAN_SAN FOREIGN KEY (ID_SAN_DET) REFERENCES SANDWICH (ID_SAN) ON DELETE CASCADE,
    CONSTRAINT FK_DET_SAN_PRO FOREIGN KEY (ID_PRO_DET) REFERENCES PRODUCTOS (ID_PRO),
    CONSTRAINT CHK_CANTIDAD_DET_SAN CHECK (CANTIDAD_DET > 0),
    CONSTRAINT CHK_OBLIGATORIO_DET CHECK (OBLIGATORIO_DET IN ('S', 'N'))
);

CREATE TABLE MENUS (
    ID_MEN NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_MEN VARCHAR2 (30) NOT NULL UNIQUE,
    NOMBRE_MEN VARCHAR2 (100) NOT NULL,
    PRECIO_MEN NUMBER (10, 2) NOT NULL,
    ACTIVO_MEN VARCHAR2 (1) DEFAULT 'A' NOT NULL,
    CONSTRAINT CHK_PRECIO_MEN CHECK (PRECIO_MEN >= 0),
    CONSTRAINT CHK_ACTIVO_MEN CHECK (ACTIVO_MEN IN ('A', 'I'))
);

CREATE TABLE DETALLE_MENU (
    ID_DET_MEN NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_MEN_DET NUMBER NOT NULL,
    TIPO_ITEM_DET VARCHAR2 (1) NOT NULL,
    ID_ITEM_DET NUMBER NOT NULL,
    CANTIDAD_DET NUMBER (10, 2) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_DET_MEN FOREIGN KEY (ID_MEN_DET) REFERENCES MENUS (ID_MEN) ON DELETE CASCADE,
    CONSTRAINT CHK_CANTIDAD_DET_MEN CHECK (CANTIDAD_DET > 0),
    CONSTRAINT CHK_TIPO_ITEM_DET_MEN CHECK (TIPO_ITEM_DET IN ('S', 'P'))
);

CREATE TABLE INVENTARIO_MOVIMIENTOS (
    ID_IMO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PRO_IMO NUMBER NOT NULL,
    FECHA_IMO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CANTIDAD_IMO NUMBER (10, 2) NOT NULL,
    TIPO_MOVIMIENTO_IMO VARCHAR2 (30) NOT NULL,
    CONSTRAINT FK_IMO_PRO FOREIGN KEY (ID_PRO_IMO) REFERENCES PRODUCTOS (ID_PRO),
    CONSTRAINT CHK_CANTIDAD_IMO CHECK (CANTIDAD_IMO > 0)
);

CREATE TABLE PEDIDOS (
    ID_PED NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLI_PED NUMBER NOT NULL,
    FECHA_PED TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    TOTAL_PED NUMBER (10, 2) DEFAULT 0 NOT NULL,
    PUNTOS_OBTENIDOS_PED NUMBER DEFAULT 0 NOT NULL,
    ESTADO_PED VARCHAR2 (2) DEFAULT 'P' NOT NULL,
    CONSTRAINT FK_PED_CLI FOREIGN KEY (ID_CLI_PED) REFERENCES CLIENTES (ID_CLI),
    CONSTRAINT CHK_TOTAL_PED CHECK (TOTAL_PED >= 0),
    CONSTRAINT CHK_PUNTOS_OBT_PED CHECK (PUNTOS_OBTENIDOS_PED >= 0),
    CONSTRAINT CHK_ESTADO_PED CHECK (ESTADO_PED IN ('P', 'C', 'E', 'A'))
);

CREATE TABLE DETALLES_PEDIDO (
    ID_DET NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PED_DET NUMBER NOT NULL,
    TIPO_ITEM_DET VARCHAR2 (1) NOT NULL,
    ID_ITEM_DET NUMBER NOT NULL,
    CANTIDAD_DET NUMBER (10, 2) NOT NULL,
    PRECIO_UNITARIO_DET NUMBER (10, 2) NOT NULL,
    SUBTOTAL_DET NUMBER (10, 2) NOT NULL,
    PUNTOS_GENERADOS_DET NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT FK_DET_PED FOREIGN KEY (ID_PED_DET) REFERENCES PEDIDOS (ID_PED) ON DELETE CASCADE,
    CONSTRAINT CHK_CANTIDAD_DET_PED CHECK (CANTIDAD_DET > 0),
    CONSTRAINT CHK_PRECIO_UNIT_DET CHECK (PRECIO_UNITARIO_DET >= 0),
    CONSTRAINT CHK_SUBTOTAL_DET CHECK (SUBTOTAL_DET >= 0),
    CONSTRAINT CHK_PUNTOS_GEN_DET CHECK (PUNTOS_GENERADOS_DET >= 0),
    CONSTRAINT CHK_TIPO_ITEM_DET_PED CHECK (TIPO_ITEM_DET IN ('S', 'M', 'P'))
);

CREATE TABLE PAGOS (
    ID_PAG NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PED_PAG NUMBER NOT NULL UNIQUE,
    FECHA_PAG TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    METODO_PAGO_PAG VARCHAR2 (2) NOT NULL,
    MONTO_RECIBIDO_PAG NUMBER (10, 2) NOT NULL,
    CAMBIO_PAG NUMBER (10, 2) DEFAULT 0 NOT NULL,
    NUMERO_REFERENCIA_PAG VARCHAR2 (50),
    ESTADO_PAGO_PAG VARCHAR2 (2) NOT NULL,
    CONSTRAINT FK_PAGO_PED FOREIGN KEY (ID_PED_PAG) REFERENCES PEDIDOS (ID_PED),
    CONSTRAINT CHK_MONTO_REC_PAG CHECK (MONTO_RECIBIDO_PAG >= 0),
    CONSTRAINT CHK_CAMBIO_PAG CHECK (CAMBIO_PAG >= 0),
    CONSTRAINT CHK_METODO_PAGO_PAG CHECK (METODO_PAGO_PAG IN ('E', 'TC', 'TF')),
    CONSTRAINT CHK_ESTADO_PAGO_PAG CHECK (ESTADO_PAGO_PAG IN ('P', 'A'))
);

CREATE TABLE RECOMPENSAS (
    ID_REC NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_REC VARCHAR2 (100) NOT NULL,
    PUNTOS_REQUERIDOS_REC NUMBER NOT NULL,
    TIPO_ITEM_REC VARCHAR2 (1) NOT NULL,
    ID_ITEM_REC NUMBER NOT NULL,
    ACTIVO_REC VARCHAR2 (1) DEFAULT 'A' NOT NULL,
    CONSTRAINT CHK_PUNTOS_REQ_REC CHECK (PUNTOS_REQUERIDOS_REC > 0),
    CONSTRAINT CHK_TIPO_ITEM_REC CHECK (TIPO_ITEM_REC IN ('S', 'M', 'P')),
    CONSTRAINT CHK_ACTIVO_REC CHECK (ACTIVO_REC IN ('A', 'I'))
);

CREATE TABLE CANJES (
    ID_CAN NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLI_CAN NUMBER NOT NULL,
    ID_REC_CAN NUMBER NOT NULL,
    FECHA_CAN TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PUNTOS_RECOMPENSA_CAN NUMBER NOT NULL,
    CONSTRAINT FK_CAN_CLI FOREIGN KEY (ID_CLI_CAN) REFERENCES CLIENTES (ID_CLI),
    CONSTRAINT FK_CAN_REC FOREIGN KEY (ID_REC_CAN) REFERENCES RECOMPENSAS (ID_REC),
    CONSTRAINT CHK_PUNTOS_CAN CHECK (PUNTOS_RECOMPENSA_CAN > 0)
);

CREATE TABLE HISTORIAL_PUNTOS (
    ID_HIS NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLI_HIS NUMBER NOT NULL,
    FECHA_HIS TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    TIPO_OPERACION_HIS VARCHAR2 (1) NOT NULL,
    PUNTOS_HIS NUMBER NOT NULL,
    REFERENCIA_HIS VARCHAR2 (100) NOT NULL,
    CONSTRAINT FK_HIS_CLI FOREIGN KEY (ID_CLI_HIS) REFERENCES CLIENTES (ID_CLI),
    CONSTRAINT CHK_TIPO_OPERACION_HIS CHECK (TIPO_OPERACION_HIS IN ('E', 'S'))
);

